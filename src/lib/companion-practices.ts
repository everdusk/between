export function findPractice(message: string, previousReply = "") {
  const text = message
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ")
    .trim();
  if (
    /^(?:запиши|сохрани|запомни|не записывай|не хочу (?:обсуждать|рассуждать|порассуждать)|оставим тему|давай сменим тему)/u.test(
      text,
    )
  )
    return;
  const direct = practices.find(practice => practice.cue.test(text) ||
    (practice.id === "self-judgment" && comparesSelf(text)));
  if (direct) return direct;
  // A short answer may only identify the person referred to by the previous question.
  if (
    /(?:чь(?:ей|его|я|е|ё) (?:мнени|реакци|оценк)|кто-то конкретный)/iu.test(
      previousReply,
    ) &&
    /^(?:ну |да[, ]+|есть |один |одна |мой |моя |наверное[, ]+)*(?:друг|подруг[аи]|мам[ауы]|отец|отца|начальник|коллега)[.! ]*$/u.test(
      text,
    )
  ) {
    return practices.find((practice) => practice.id === "judgment");
  }
}

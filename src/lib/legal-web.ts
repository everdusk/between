const BINDING = "Если формулировки разойдутся, главный текст — на русском языке.";

type Pair = [heading: string, paragraphs: string[]];

function webDoc(title: string, updated: string, preface: string[], sections: Pair[], binding = false): LegalDoc {
  return {
    title,
    updated,
    preface,
    sections: sections.map(([heading, paragraphs], index) => ({
      heading,
      paragraphs: binding && index === 0 ? [...paragraphs, BINDING] : paragraphs,
    })),
  };
}

